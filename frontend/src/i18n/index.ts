// Lightweight i18n for ApplyEase frontend.
// Supported languages: Simplified Chinese (zh-CN), Traditional Chinese (zh-TW), English (en).
// Default language is English.

export type Language = "zh-CN" | "zh-TW" | "en";

export const LANGUAGES: Array<{ code: Language; label: string }> = [
  { code: "zh-CN", label: "简体中文" },
  { code: "zh-TW", label: "繁體中文" },
  { code: "en", label: "English" },
];

export const DEFAULT_LANGUAGE: Language = "en";

const STORAGE_KEY = "applyease:language";
const LANGUAGE_PATHS: Record<Language, string> = {
  "zh-CN": "zh-cn",
  "zh-TW": "zh-tw",
  en: "en",
};
const PATH_LANGUAGES: Record<string, Language> = {
  "zh-cn": "zh-CN",
  "zh-tw": "zh-TW",
  en: "en",
};

function languageFromPath(): Language | null {
  try {
    const first = window.location.pathname
      .split("/")
      .filter(Boolean)[0]
      ?.toLowerCase();
    return first ? (PATH_LANGUAGES[first] ?? null) : null;
  } catch {
    return null;
  }
}

export function detectLanguage(): Language {
  const fromPath = languageFromPath();
  if (fromPath) return fromPath;

  try {
    const stored = localStorage.getItem(STORAGE_KEY);

    if (stored === "zh-CN" || stored === "zh-TW" || stored === "en")
      return stored;
  } catch {
    // ignore
  }

  return DEFAULT_LANGUAGE;
}

export function saveLanguage(language: Language): void {
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // ignore
  }

  // Keep a shareable, reload-safe language path. This is a path segment—not a
  // separate DNS domain—so the SPA can be served from the same deployment.
  try {
    const url = new URL(window.location.href);
    const parts = url.pathname.split("/").filter(Boolean);
    if (parts[0]?.toLowerCase() in PATH_LANGUAGES) parts.shift();
    url.pathname = `/${LANGUAGE_PATHS[language]}${parts.length ? `/${parts.join("/")}` : ""}`;
    window.history.pushState({}, "", `${url.pathname}${url.search}${url.hash}`);
  } catch {
    // Language selection must still work if History API is unavailable.
  }
}


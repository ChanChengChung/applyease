const dictionaries: Record<Language, Dict> = {
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  en,
};

type Vars = Record<string, string | number>;

export function translate(
  language: Language,
  key: string,
  vars?: Vars,
): string {
  const dict = dictionaries[language] ?? en;

  const template = dict[key] ?? en[key] ?? key;

  if (!vars) return template;

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name)
      ? String(vars[name])
      : match,
  );
}

/** Used by tests to stop newly-added English keys silently falling back in Chinese UI. */
export function missingTranslationKeys(
  language: Exclude<Language, "en">,
): string[] {
  return Object.keys(en).filter(
    (key) => !Object.prototype.hasOwnProperty.call(dictionaries[language], key),
  );
}
